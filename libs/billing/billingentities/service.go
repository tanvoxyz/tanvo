// dunningCampaign sets the applied dunning campaign of be from in; a zero
// ref removes it, a missing campaign is not found (dunning_campaign).
//
// source: app/services/billing_entities/update_applied_dunning_campaign_service.rb:12-26
func (s *Service) dunningCampaign(ctx context.Context, r port.Repos, be *organization.BillingEntity, in Input) error {
	if !in.AppliedDunningCampaign.Set {
		return nil
	}
	if in.AppliedDunningCampaign.Value.IsZero() {
		be.AppliedDunningCampaignID = core.DunningCampaignID{}
		return nil
	}
	c, err := dunningCampaigns(r, be.OrganizationID).One(ctx, in.AppliedDunningCampaign.Value)
	if err != nil {
		return err
	}
	be.AppliedDunningCampaignID = c.ID
	return nil
}

// resetDunningAttempts clears the dunning attempts of the entity's
// customers falling back to its dunning campaign.
//
// source: app/models/billing_entity.rb:147-155
func (s *Service) resetDunningAttempts(ctx context.Context, r port.Repos, be *organization.BillingEntity) error {
	now := s.d.Now()
	for page := (core.PageRequest{Size: core.MaxPageSize}); ; {
		p, err := r.Customers.ListForDunning(ctx, be.OrganizationID, core.DunningCampaignID{}, page)
		if err != nil {
			return fmt.Errorf("list customers: %w", err)
		}
		for _, c := range p.Items {
			if c.BillingEntityID != be.ID || (len(c.DunningCampaignAttempts) == 0 && c.LastDunningCampaignAttemptAt == nil) {
				continue
			}
			c.DunningCampaignAttempts = map[string]int{}
			c.LastDunningCampaignAttemptAt = nil
			c.UpdatedAt = now
			if err := r.Customers.Update(ctx, c); err != nil {
				return fmt.Errorf("reset dunning attempts of customer %s: %w", c.ID, err)
			}
		}
		if p.NextToken == "" {
			return nil
		}
		page.Token = p.NextToken
	}
}

// generateEUTaxes creates or updates the organization's EU VAT taxes.
//
// source: app/services/taxes/auto_generate_service.rb:12-60
func (s *Service) generateEUTaxes(ctx context.Context, r port.Repos, org core.OrganizationID, now time.Time) error {
	for _, t := range tax.EUTaxes(now) {
		existing, err := r.Taxes.GetByCode(ctx, org, t.Code)
		switch {
		case errors.Is(err, core.ErrNotFound):
			err = r.Taxes.Create(ctx, &catalog.Tax{
				ID:             core.NewID[core.TaxID](s.d.IDs),
				OrganizationID: org,
				Code:           t.Code,
				Name:           t.Name,
				Rate:           t.Rate,
				Description:    new(euTaxDescription),
				AutoGenerated:  true,
				CreatedAt:      now,
				UpdatedAt:      now,
			})
		case err == nil:
			existing.Name, existing.Rate = t.Name, t.Rate
			existing.Description, existing.AutoGenerated = new(euTaxDescription), true
			existing.UpdatedAt = now
			err = r.Taxes.Update(ctx, existing)
		}
		if err != nil {
			return fmt.Errorf("generate tax %s: %w", t.Code, err)
		}
	}
	return nil
}

// updateDrafts carries the changes from prev to be over the entity's
// draft invoices.
//
// source: app/services/billing_entities/update_invoice_payment_due_date_service.rb:14-30
// source: app/services/invoices/update_issuing_date_from_billing_entity_service.rb:13-62
func (s *Service) updateDrafts(ctx context.Context, r port.Repos, prev, be *organization.BillingEntity, in Input) error {
	termChanged := be.NetPaymentTermDays != prev.NetPaymentTermDays
	issuingChanged := be.IssuingDateAnchor != prev.IssuingDateAnchor ||
		be.IssuingDateAdjustment != prev.IssuingDateAdjustment ||
		be.InvoiceGracePeriodDays != prev.InvoiceGracePeriodDays
	refresh := in.Taxes.Set && !slices.Equal(be.TaxIDs, prev.TaxIDs)
	if !termChanged && !issuingChanged && !refresh {
		return nil
	}
	oldDefaults, newDefaults := kernel.DefaultsOf(prev), kernel.DefaultsOf(be)
	customers := map[core.CustomerID]*customer.Customer{}
	now := s.d.Now()
	f := invoice.Filter{BillingEntityID: be.ID, Statuses: []invoice.Status{invoice.StatusDraft}}
	for page := (core.PageRequest{Size: core.MaxPageSize}); ; {
		p, err := r.Invoices.List(ctx, be.OrganizationID, f, page)
		if err != nil {
			return fmt.Errorf("list draft invoices: %w", err)
		}
		for _, inv := range p.Items {
			c, ok := customers[inv.CustomerID]
			if !ok {
				if c, err = r.Customers.Get(ctx, be.OrganizationID, inv.CustomerID); err != nil {
					return fmt.Errorf("load customer %s: %w", inv.CustomerID, err)
				}
				customers[inv.CustomerID] = c
			}
			// The payment due date of the customers without a term of
			// their own follows the entity's.
			if termChanged && c.NetPaymentTermDays == nil {
				inv.NetPaymentTermDays = be.NetPaymentTermDays
				inv.PaymentDueDate = invoice.PaymentDueDate(inv.IssuingDate, be.NetPaymentTermDays)
			}
			if issuingChanged {
				if err := s.reissue(ctx, r, inv, c, oldDefaults, newDefaults); err != nil {
					return err
				}
			}
			if refresh {
				inv.RefreshRequested = true
			}
			inv.UpdatedAt = now
			if err := r.Invoices.Update(ctx, inv); err != nil {
				return fmt.Errorf("update draft invoice %s: %w", inv.ID, err)
			}
		}
		if p.NextToken == "" {
			return nil
		}
		page.Token = p.NextToken
	}
}

// reissue moves the dates of the draft inv of customer c from the issuing
// date settings before to after.
//
// source: app/services/invoices/update_issuing_date_from_billing_entity_service.rb:13-62
func (s *Service) reissue(ctx context.Context, r port.Repos, inv *invoice.Invoice, c *customer.Customer, before, after customer.Defaults) error {
	subs, err := r.InvoiceSubscriptions.ListByInvoice(ctx, inv.OrganizationID, inv.ID)
	if err != nil {
		return fmt.Errorf("load invoice subscriptions of %s: %w", inv.ID, err)
	}
	recurring := len(subs) > 0 && subs[0].Recurring
	facts := func(d customer.Defaults) invoice.IssuingDateFacts {
		return invoice.IssuingDateFacts{
			Recurring:       recurring,
			Anchor:          c.ApplicableIssuingDateAnchor(d),
			Adjustment:      c.ApplicableIssuingDateAdjustment(d),
			GracePeriodDays: c.ApplicableGracePeriodDays(d),
		}
	}
	oldFacts, newFacts := facts(before), facts(after)
	inv.IssuingDate = inv.IssuingDate.AddDays(invoice.IssuingDateOffset(newFacts) - invoice.IssuingDateOffset(oldFacts))
	inv.ExpectedFinalizationDate = inv.ExpectedFinalizationDate.AddDays(newFacts.GracePeriodDays - oldFacts.GracePeriodDays)
	inv.AppliedGracePeriodDays = newFacts.GracePeriodDays
	inv.PaymentDueDate = invoice.PaymentDueDate(inv.IssuingDate, c.ApplicableNetPaymentTermDays(after))
	return nil
}

// putLogo stores the logo of in and sets it on be, returning the stored
// reference; an empty logo removes be's.
//
// source: app/services/billing_entities/update_service.rb:130-150
func (s *Service) putLogo(ctx context.Context, org core.OrganizationID, be *organization.BillingEntity, in Input) (core.BlobRef, error) {
	if !in.Logo.Set {
		return "", nil
	}
	if len(in.Logo.Value) == 0 {
		be.Logo = ""
		return "", nil
	}
	if s.blobs == nil {
		return "", core.NewRuleError(CodeLogoStorageNotConfigured, "logos cannot be stored: no blob store is configured")
	}
	t := logoType(in.Logo.Value)
	ref, err := s.blobs.Put(ctx, org, "logo."+strings.TrimPrefix(t, "image/"), t, bytes.NewReader(in.Logo.Value))
	if err != nil {
		return "", fmt.Errorf("store logo: %w", err)
	}
	be.Logo = ref
	return ref, nil
}

// dropLogo deletes a logo no longer referenced; a failure is only logged,
// leaving an orphan file.
func (s *Service) dropLogo(ctx context.Context, org core.OrganizationID, ref core.BlobRef) {
	if ref.IsZero() || s.blobs == nil {
		return
	}
	if err := s.blobs.Delete(ctx, org, ref); err != nil {
		s.logger().WarnContext(ctx, "delete billing entity logo", "organization_id", org.String(), "error", err)
	}
}

// logActivity records the activity log of be, whose attributes before an
// update are prev (lago activity_loggable of create_service.rb:14 and
// update_service.rb:14).
func (s *Service) logActivity(ctx context.Context, r port.Repos, t auditlog.ActivityType, prev, be *organization.BillingEntity) error {
	a := auditlog.Activity{Type: t, OrganizationID: be.OrganizationID, ResourceType: auditlog.ResourceBillingEntity, ResourceID: be.ID.UUID()}
	var err error
	if a.Object, err = auditlog.ObjectOf(be); err != nil {
		return err
	}
	if prev != nil {
		if a.Before, err = auditlog.ObjectOf(prev); err != nil {
			return err
		}
	}
	return s.d.LogActivity(ctx, r, a)
}

func (s *Service) logger() *slog.Logger {
	if s.d.Logger != nil {
		return s.d.Logger
	}
	return slog.Default()
}

// read runs fn in a transaction and returns its value.
func read[T any](ctx context.Context, d *kernel.Deps, fn func(context.Context, port.Repos) (T, error)) (T, error) {
	var out T
	err := d.Tx.InTx(ctx, func(ctx context.Context, r port.Repos) error {
		v, err := fn(ctx, r)
		out = v
		return err
	})
	return out, err
}

// notFound turns a missing entity into core.NotFound("billing_entity").
func notFound(err error) error {
	if errors.Is(err, core.ErrNotFound) {
		return core.NotFound(Resource)
	}
	return err
}

// codeConflict turns a uniqueness violation, which a concurrent write can
// still cause after the code check, into code value_already_exist.
func codeConflict(err error) error {
	if errors.Is(err, core.ErrConflict) {
		return fieldError("code", core.CodeAlreadyExists)
	}
	return err
}

func fieldError(field, code string) error {
	return &core.ValidationError{Errors: []core.FieldError{{Field: field, Code: code}}}
}
