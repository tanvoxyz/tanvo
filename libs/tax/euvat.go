//go:embed data/eu_vat_rates.json
var euVATRatesJSON []byte

// Codes of the taxes generated for EU VAT.
const (
	// EUTaxCodePrefix starts the code of every generated EU VAT tax.
	EUTaxCodePrefix = "tanvo_eu_"
	// EUTaxCodeReverseCharge is the 0 % tax of intra-EU B2B sales across
	// borders, the buyer self-accounting the VAT.
	EUTaxCodeReverseCharge = EUTaxCodePrefix + "reverse_charge"
	// EUTaxCodeExempt is the 0 % tax of sales outside the EU.
	EUTaxCodeExempt = EUTaxCodePrefix + "tax_exempt"
)

// euTaxDescription describes the generated EU VAT taxes.
const euTaxDescription = "Generated by Tanvo EU VAT management"

// EUException is a territory of an EU country with its own VAT (or none),
// told apart by its postcodes.
type EUException struct {
	// Name is the territory's name ("Canary Islands").
	Name string
	// Postcode matches the territory's postcodes, anywhere in a postcode
	// stripped of whitespace.
	Postcode *regexp.Regexp
	// Standard is the territory's standard rate in percent.
	Standard money.Decimal
}

// Code is the code fragment of the exception's tax ("canary_islands").
func (e EUException) Code() string {
	return underscore(parameterize(e.Name, "-"))
}

// EURates are the VAT rates of an EU country for a period.
type EURates struct {
	// EffectiveFrom is the first day (UTC) the rates apply.
	EffectiveFrom time.Time
	// Rates are the rates in percent by kind ("standard", "reduced"…).
	Rates map[string]money.Decimal
	// Exceptions are the country's territories with their own VAT.
	Exceptions []EUException
}

// Standard is the standard rate in percent.
func (r EURates) Standard() money.Decimal { return r.Rates["standard"] }

type euTable struct {
	countries []string
	periods   map[string][]EURates // newest first
}

// euRates parses the embedded table once. The table is constant, so the
// cached value is not mutable state.
var euRates = sync.OnceValues(func() (euTable, error) {
	var raw struct {
		Items map[string][]struct {
			EffectiveFrom string                     `json:"effective_from"`
			Rates         map[string]json.RawMessage `json:"rates"`
			Exceptions    []struct {
				Name     string          `json:"name"`
				Postcode string          `json:"postcode"`
				Standard json.RawMessage `json:"standard"`
			} `json:"exceptions"`
		} `json:"items"`
	}
	if err := json.Unmarshal(euVATRatesJSON, &raw); err != nil {
		return euTable{}, fmt.Errorf("tax: parse EU VAT rates: %w", err)
	}
	t := euTable{periods: map[string][]EURates{}}
	for cc, periods := range raw.Items {
		t.countries = append(t.countries, cc)
		for _, p := range periods {
			from, err := time.Parse(time.DateOnly, p.EffectiveFrom)
			if err != nil {
				return euTable{}, fmt.Errorf("tax: EU VAT rates of %s: %w", cc, err)
			}
			r := EURates{EffectiveFrom: from, Rates: map[string]money.Decimal{}}
			for kind, v := range p.Rates {
				var d money.Decimal
				if err := d.UnmarshalJSON(v); err != nil {
					return euTable{}, fmt.Errorf("tax: EU VAT rate %s of %s: %w", kind, cc, err)
				}
				r.Rates[kind] = d
			}
			for _, e := range p.Exceptions {
				// The table's patterns are postcode prefixes; Lago matches them
				// anywhere in the zipcode, which lets 135000 match 35\d{3}.
				re, err := regexp.Compile(`^(?:` + e.Postcode + `)`)
				if err != nil {
					return euTable{}, fmt.Errorf("tax: EU VAT exception %s of %s: %w", e.Name, cc, err)
				}
				var d money.Decimal
				if err := d.UnmarshalJSON(e.Standard); err != nil {
					return euTable{}, fmt.Errorf("tax: EU VAT exception %s of %s: %w", e.Name, cc, err)
				}
				r.Exceptions = append(r.Exceptions, EUException{Name: e.Name, Postcode: re, Standard: d})
			}
			t.periods[cc] = append(t.periods[cc], r)
		}
		slices.SortStableFunc(t.periods[cc], func(a, b EURates) int { return b.EffectiveFrom.Compare(a.EffectiveFrom) })
	}
	slices.Sort(t.countries)
	return t, nil
})

func mustEURates() euTable {
	t, err := euRates()
	if err != nil {
		// The table is embedded and checked by the tests.
		panic(err)
	}
	return t
}

// EUCountryCodes returns the ISO 3166-1 alpha-2 codes of the EU countries,
// sorted.
func EUCountryCodes() []string {
	return slices.Clone(mustEURates().countries)
}

// IsEUCountry reports whether code (any case) is an EU country.
func IsEUCountry(code string) bool {
	_, ok := mustEURates().periods[strings.ToUpper(code)]
	return ok
}

// LookupEURates returns the VAT rates of an EU country in force at a time:
// the period with the latest start at or before it.
func LookupEURates(country string, at time.Time) (EURates, bool) {
	for _, p := range mustEURates().periods[strings.ToUpper(country)] {
		if !at.Before(p.EffectiveFrom) {
			return p, true
		}
	}
	return EURates{}, false
}

// EUStandardTaxCode is the code of a country's standard VAT tax.
func EUStandardTaxCode(country string) string {
	return EUTaxCodePrefix + strings.ToLower(country) + "_standard"
}

// EUExceptionTaxCode is the code of the VAT tax of a country's territory.
func EUExceptionTaxCode(country string, e EUException) string {
	return EUTaxCodePrefix + strings.ToLower(country) + "_exception_" + e.Code()
}

// EUTaxes returns the taxes generated for EU VAT at a time: each country's
// standard rate, each territory's standard rate, reverse charge and exempt.
func EUTaxes(at time.Time) []Tax {
	var out []Tax
	for _, cc := range EUCountryCodes() {
		r, ok := LookupEURates(cc, at)
		if !ok {
			continue
		}
		out = append(out, Tax{Code: EUStandardTaxCode(cc), Name: cc + " Standard", Description: euTaxDescription, Rate: r.Standard()})
		for _, e := range r.Exceptions {
			out = append(out, Tax{Code: EUExceptionTaxCode(cc, e), Name: cc + " " + e.Name + " Standard", Description: euTaxDescription, Rate: e.Standard})
		}
	}
	return append(out,
		Tax{Code: EUTaxCodeReverseCharge, Name: "Reverse Charge", Description: euTaxDescription, Rate: money.Zero},
		Tax{Code: EUTaxCodeExempt, Name: "Tax Exempt", Description: euTaxDescription, Rate: money.Zero},
	)
}

// b2bOnlyTerritoryCountries are the countries whose territories' VAT
// applies to business customers only.
var b2bOnlyTerritoryCountries = []string{"FR"}

// EUCustomer is what the EU VAT decision needs of a customer.
type EUCustomer struct {
	// Country is the customer's country code.
	Country string
	// Zipcode is the customer's postcode.
	Zipcode string
	// TaxIdentificationNumber is the customer's VAT number, if any.
	TaxIdentificationNumber string
}

// EUTaxInput is the input of the EU VAT decision.
type EUTaxInput struct {
	// BillingCountry is the country of the billing entity (the seller).
	BillingCountry string
	// Customer is the buyer.
	Customer EUCustomer
	// At is when the decision is made; it picks the rates.
	At time.Time
}

// EUTaxDecision is the outcome of [ResolveEUTax].
type EUTaxDecision struct {
	// TaxCode is the code of the tax to apply, empty when a VIES check is
	// required first.
	TaxCode string
	// VIESCheckRequired is set when the customer has a VAT number to check
	// with VIES; the caller checks it and calls [ResolveEUTaxAfterVIES].
	VIESCheckRequired bool
}

// EUTaxesApplicable reports whether a customer's EU VAT tax must be
// (re)decided, for a billing entity managing EU VAT: on creation, when the
// customer has no EU VAT tax yet, or when its tax attributes (country,
// zipcode, VAT number) changed.
func EUTaxesApplicable(newRecord, hasEUTax, taxAttributesChanged bool) bool {
	return newRecord || !hasEUTax || taxAttributesChanged
}

// ResolveEUTax decides a customer's EU VAT tax. A customer in a territory
// with its own VAT gets the territory's tax (for French territories, only
// business customers with a well-formed VAT number). Otherwise a customer
// with a VAT number needs a VIES check. Otherwise the customer gets the
// standard rate of their EU country, or of the billing country when they
// have none, or is exempt outside the EU.
func ResolveEUTax(in EUTaxInput) EUTaxDecision {
	if code := euTerritoryTaxCode(in); code != "" {
		return EUTaxDecision{TaxCode: code}
	}
	if in.Customer.TaxIdentificationNumber != "" {
		return EUTaxDecision{VIESCheckRequired: true}
	}
	return EUTaxDecision{TaxCode: euNonVIESTaxCode(in)}
}

// VIESResult is the outcome of a VIES check of a customer's VAT number.
type VIESResult struct {
	// Valid is set when VIES knows the number.
	Valid bool
	// CountryCode is the country VIES registered the number in.
	CountryCode string
}

// ResolveEUTaxAfterVIES decides a customer's EU VAT tax after a VIES check.
// A valid number registered in another country than the billing country is
// reverse charged; one registered in the billing country gets that
// country's standard rate, or its territory's when the zipcode matches one.
// Without a valid number the decision is as for a customer without one.
func ResolveEUTaxAfterVIES(in EUTaxInput, vies VIESResult) string {
	if !vies.Valid {
		return euNonVIESTaxCode(in)
	}
	if !strings.EqualFold(in.BillingCountry, vies.CountryCode) {
		return EUTaxCodeReverseCharge
	}
	standard := EUStandardTaxCode(in.BillingCountry)
	zip := stripSpace(in.Customer.Zipcode)
	if zip == "" {
		return standard
	}
	if e, ok := matchEUException(vies.CountryCode, zip, in.At); ok {
		return EUExceptionTaxCode(vies.CountryCode, e)
	}
	return standard
}

func euTerritoryTaxCode(in EUTaxInput) string {
	cc := strings.ToUpper(in.Customer.Country)
	zip := stripSpace(in.Customer.Zipcode)
	if cc == "" || zip == "" || !IsEUCountry(cc) {
		return ""
	}
	e, ok := matchEUException(cc, zip, in.At)
	if !ok {
		return ""
	}
	if slices.Contains(b2bOnlyTerritoryCountries, cc) {
		tin := in.Customer.TaxIdentificationNumber
		if tin == "" || !ValidVATNumberSyntax(tin) {
			return ""
		}
	}
	return EUExceptionTaxCode(cc, e)
}

func euNonVIESTaxCode(in EUTaxInput) string {
	switch {
	case in.Customer.Country == "":
		return EUStandardTaxCode(in.BillingCountry)
	case IsEUCountry(in.Customer.Country):
		return EUStandardTaxCode(in.Customer.Country)
	default:
		return EUTaxCodeExempt
	}
}

func matchEUException(country, zip string, at time.Time) (EUException, bool) {
	r, ok := LookupEURates(country, at)
	if !ok {
		return EUException{}, false
	}
	for _, e := range r.Exceptions {
		if e.Postcode.MatchString(zip) {
			return e, true
		}
	}
	return EUException{}, false
}

func stripSpace(s string) string {
	return strings.Map(func(r rune) rune {
		if r == ' ' || r == '\t' || r == '\n' || r == '\r' || r == '\f' || r == '\v' {
			return -1
		}
		return r
	}, s)
}
