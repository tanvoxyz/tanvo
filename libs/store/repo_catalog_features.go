func (r featureRepo) ListByIDs(ctx context.Context, org core.OrganizationID, ids []core.FeatureID) ([]*catalog.Feature, error) {
	q, err := r.t.queries(ctx, org)
	if err != nil {
		return nil, err
	}
	rows, err := q.ListFeaturesByIDs(ctx, db.ListFeaturesByIDsParams{OrganizationID: org.UUID(), Ids: uuids(ids)})
	if err != nil {
		return nil, fmt.Errorf("list features: %w", mapErr(err))
	}
	features := make([]*catalog.Feature, len(rows))
	byID := make(map[core.FeatureID]*catalog.Feature, len(rows))
	for i, row := range rows {
		features[i] = featureOf(row)
		byID[features[i].ID] = features[i]
	}
	if err := r.withPrivileges(ctx, q, org, features); err != nil {
		return nil, err
	}
	out, err := catalogFeaturesInOrder("feature", ids, byID)
	if err != nil {
		return nil, err
	}
	// A repeated ID must not share the privileges slice of another item.
	seen := make(map[core.FeatureID]bool, len(out))
	for i, f := range out {
		if seen[f.ID] {
			c := *f
			c.Privileges = append([]catalog.Privilege(nil), f.Privileges...)
			out[i] = &c
		}
		seen[f.ID] = true
	}
	return out, nil
}

func (r featureRepo) List(ctx context.Context, org core.OrganizationID, page core.PageRequest) (core.Page[*catalog.Feature], error) {
	q, err := r.t.queries(ctx, org)
	if err != nil {
		return core.Page[*catalog.Feature]{}, err
	}
	after, lim, err := pageArgs(page)
	if err != nil {
		return core.Page[*catalog.Feature]{}, err
	}
	rows, err := q.ListFeatures(ctx, db.ListFeaturesParams{OrganizationID: org.UUID(), After: after, Lim: lim})
	if err != nil {
		return core.Page[*catalog.Feature]{}, fmt.Errorf("list features: %w", mapErr(err))
	}
	out, err := pageOf(rows, page,
		func(r db.Feature) (*catalog.Feature, error) { return featureOf(r), nil },
		func(f *catalog.Feature) string { return f.ID.String() })
	if err != nil {
		return core.Page[*catalog.Feature]{}, err
	}
	if err := r.withPrivileges(ctx, q, org, out.Items); err != nil {
		return core.Page[*catalog.Feature]{}, err
	}
	return out, nil
}

// entitlementRepo implements catalog.EntitlementRepository.
type entitlementRepo struct{ t *txState }

var _ catalog.EntitlementRepository = entitlementRepo{}

func entitlementParams(e *catalog.Entitlement) (db.CreateEntitlementParams, error) {
	values := e.Values
	if values == nil {
		values = map[string]string{}
	}
	b, err := encodeJSON(values)
	if err != nil {
		return db.CreateEntitlementParams{}, fmt.Errorf("entitlement %s: %w", e.ID, err)
	}
	return db.CreateEntitlementParams{
		OrganizationID:  e.OrganizationID.UUID(),
		ID:              e.ID.UUID(),
		FeatureID:       e.FeatureID.UUID(),
		PlanID:          optUUID(e.PlanID),
		SubscriptionID:  optUUID(e.SubscriptionID),
		PrivilegeValues: b,
		CreatedAt:       utc(e.CreatedAt),
		UpdatedAt:       utc(e.UpdatedAt),
	}, nil
}

func entitlementOf(r db.Entitlement) (*catalog.Entitlement, error) {
	var values map[string]string
	if err := decodeJSON(r.PrivilegeValues, &values); err != nil {
		return nil, fmt.Errorf("entitlement %s: %w", r.ID, err)
	}
	if len(values) == 0 {
		values = nil
	}
	return &catalog.Entitlement{
		ID:             idOf[core.EntitlementID](r.ID),
		OrganizationID: idOf[core.OrganizationID](r.OrganizationID),
		FeatureID:      idOf[core.FeatureID](r.FeatureID),
		PlanID:         optIDOf[core.PlanID](r.PlanID),
		SubscriptionID: optIDOf[core.SubscriptionID](r.SubscriptionID),
		Values:         values,
		CreatedAt:      utc(r.CreatedAt),
		UpdatedAt:      utc(r.UpdatedAt),
	}, nil
}

func entitlementRemovalOf(r db.EntitlementRemoval) (*catalog.EntitlementRemoval, error) {
	return &catalog.EntitlementRemoval{
		ID:             idOf[core.EntitlementRemovalID](r.ID),
		OrganizationID: idOf[core.OrganizationID](r.OrganizationID),
		SubscriptionID: idOf[core.SubscriptionID](r.SubscriptionID),
		FeatureID:      idOf[core.FeatureID](r.FeatureID),
		PrivilegeCode:  r.PrivilegeCode,
		CreatedAt:      utc(r.CreatedAt),
	}, nil
}

