// featureRepo implements catalog.FeatureRepository. A feature's
// privileges are rows of feature_privileges, rewritten with the feature.
type featureRepo struct{ t *txState }

var _ catalog.FeatureRepository = featureRepo{}

func featureParams(f *catalog.Feature) db.CreateFeatureParams {
	return db.CreateFeatureParams{
		OrganizationID: f.OrganizationID.UUID(),
		ID:             f.ID.UUID(),
		Code:           f.Code,
		Name:           f.Name,
		Description:    f.Description,
		CreatedAt:      utc(f.CreatedAt),
		UpdatedAt:      utc(f.UpdatedAt),
	}
}

func featureOf(r db.Feature) *catalog.Feature {
	return &catalog.Feature{
		ID:             idOf[core.FeatureID](r.ID),
		OrganizationID: idOf[core.OrganizationID](r.OrganizationID),
		Code:           r.Code,
		Name:           r.Name,
		Description:    r.Description,
		CreatedAt:      utc(r.CreatedAt),
		UpdatedAt:      utc(r.UpdatedAt),
	}
}

func privilegeOf(r db.FeaturePrivilege) catalog.Privilege {
	var opts []string
	if len(r.SelectOptions) > 0 {
		opts = r.SelectOptions
	}
	return catalog.Privilege{
		ID:            idOf[core.PrivilegeID](r.ID),
		Code:          r.Code,
		Name:          r.Name,
		ValueType:     catalog.PrivilegeValueType(r.ValueType),
		SelectOptions: opts,
	}
}

// writePrivileges replaces the privileges of f.
func (r featureRepo) writePrivileges(ctx context.Context, q *db.Queries, f *catalog.Feature, replace bool) error {
	org, id := f.OrganizationID.UUID(), f.ID.UUID()
	if replace {
		if err := q.DeleteFeaturePrivileges(ctx, db.DeleteFeaturePrivilegesParams{OrganizationID: org, FeatureID: id}); err != nil {
			return err
		}
	}
	for i, p := range f.Privileges {
		opts := p.SelectOptions
		if opts == nil {
			opts = []string{}
		}
		if err := q.InsertFeaturePrivilege(ctx, db.InsertFeaturePrivilegeParams{
			OrganizationID: org,
			ID:             p.ID.UUID(),
			FeatureID:      id,
			Position:       int32(i), //nolint:gosec // privileges per feature are few
			Code:           p.Code,
			Name:           p.Name,
			ValueType:      string(p.ValueType),
			SelectOptions:  opts,
		}); err != nil {
			return err
		}
	}
	return nil
}

// withPrivileges loads the privileges of features.
func (r featureRepo) withPrivileges(ctx context.Context, q *db.Queries, org core.OrganizationID, features []*catalog.Feature) error {
	if len(features) == 0 {
		return nil
	}
	ids := make([]uuid.UUID, len(features))
	byID := make(map[uuid.UUID]*catalog.Feature, len(features))
	for i, f := range features {
		ids[i] = f.ID.UUID()
		byID[ids[i]] = f
	}
	rows, err := q.ListFeaturePrivileges(ctx, db.ListFeaturePrivilegesParams{OrganizationID: org.UUID(), FeatureIds: ids})
	if err != nil {
		return fmt.Errorf("list feature privileges: %w", mapErr(err))
	}
	for _, row := range rows {
		if f := byID[row.FeatureID]; f != nil {
			f.Privileges = append(f.Privileges, privilegeOf(row))
		}
	}
	return nil
}

