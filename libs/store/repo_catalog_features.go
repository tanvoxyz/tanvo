func (r taxRepo) List(ctx context.Context, org core.OrganizationID, f catalog.TaxFilter, page core.PageRequest) (core.Page[*catalog.Tax], error) {
	q, err := r.t.queries(ctx, org)
	if err != nil {
		return core.Page[*catalog.Tax]{}, err
	}
	after, lim, err := pageArgs(page)
	if err != nil {
		return core.Page[*catalog.Tax]{}, err
	}
	rows, err := q.ListTaxes(ctx, db.ListTaxesParams{
		OrganizationID: org.UUID(), AutoGenerated: f.AutoGenerated, After: after, Lim: lim,
	})
	if err != nil {
		return core.Page[*catalog.Tax]{}, fmt.Errorf("list taxes: %w", mapErr(err))
	}
	return pageOf(rows, page, taxOf, func(x *catalog.Tax) string { return x.ID.String() })
}

