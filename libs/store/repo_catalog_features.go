func (r taxRepo) List(ctx context.Context, org core.OrganizationID, f catalog.TaxFilter, page core.PageRequest) (core.Page[*catalog.Tax], error) {
	q, err := r.t.queries(ctx, org)
	if err != nil {
		return core.Page[*catalog.Tax]{}, err
	}
	if !f.Order.Valid() {
		return core.Page[*catalog.Tax]{}, fmt.Errorf("list taxes: %w: order", core.ErrInvalidValue)
	}
	byName := f.Order == core.OrderRecent
	var (
		after     *uuid.UUID
		afterName *string
		afterAt   *time.Time
		lim       int32
	)
	if byName {
		after, afterName, afterAt, lim, err = nameCursorArgs(page)
	} else {
		after, lim, err = pageArgs(page)
	}
	if err != nil {
		return core.Page[*catalog.Tax]{}, err
	}
	rows, err := q.ListTaxes(ctx, db.ListTaxesParams{
		OrganizationID: org.UUID(), AutoGenerated: f.AutoGenerated, AppliedToOrganization: f.AppliedToOrganization, Search: searchArg(f.Search),
		After: after, ByName: byName, AfterName: afterName, AfterAt: afterAt, Lim: lim,
	})
	if err != nil {
		return core.Page[*catalog.Tax]{}, fmt.Errorf("list taxes: %w", mapErr(err))
	}
	return pageOf(rows, page, taxOf, func(x *catalog.Tax) string {
		if byName {
			return nameToken(x.Name, x.CreatedAt, x.ID.UUID())
		}
		return x.ID.String()
	})
}

