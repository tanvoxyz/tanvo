// bindCatalogFeatures binds the repositories of taxes, commitments, usage
// thresholds, features and entitlements.
func (t *txState) bindCatalogFeatures(r *port.Repos) {
	r.Taxes = taxRepo{t}
	r.Commitments = commitmentRepo{t}
	r.UsageThresholds = usageThresholdRepo{t}
	r.Features = featureRepo{t}
	r.Entitlements = entitlementRepo{t}
}

// catalogFeaturesInOrder returns the rows of byKey in the order of keys; a
// key without a row fails with core.ErrNotFound naming entity.
func catalogFeaturesInOrder[K comparable, T any](entity string, keys []K, byKey map[K]T) ([]T, error) {
	out := make([]T, 0, len(keys))
	for _, k := range keys {
		v, ok := byKey[k]
		if !ok {
			return nil, notFound(entity, k)
		}
		out = append(out, v)
	}
	return out, nil
}

// taxRepo implements catalog.TaxRepository.
type taxRepo struct{ t *txState }

var _ catalog.TaxRepository = taxRepo{}

func taxParams(x *catalog.Tax) db.CreateTaxParams {
	p := db.CreateTaxParams{
		OrganizationID: x.OrganizationID.UUID(),
		ID:             x.ID.UUID(),
		Code:           x.Code,
		Name:           x.Name,
		Description:    x.Description,
		AutoGenerated:  x.AutoGenerated,
		CreatedAt:      utc(x.CreatedAt),
		Rate:           x.Rate,
		UpdatedAt:      utc(x.UpdatedAt),
	}
	return p
}

func taxOf(r db.Tax) (*catalog.Tax, error) {
	return &catalog.Tax{
		ID:             idOf[core.TaxID](r.ID),
		OrganizationID: idOf[core.OrganizationID](r.OrganizationID),
		Code:           r.Code,
		Name:           r.Name,
		Rate:           r.Rate,
		Description:    r.Description,
		AutoGenerated:  r.AutoGenerated,
		CreatedAt:      utc(r.CreatedAt),
		UpdatedAt:      utc(r.UpdatedAt),
	}, nil
}

func (r taxRepo) Create(ctx context.Context, x *catalog.Tax) error {
	q, err := r.t.queries(ctx, x.OrganizationID)
	if err != nil {
		return err
	}
	n, err := q.CreateTax(ctx, taxParams(x))
	return insertErr("tax", n, err)
}

func (r taxRepo) Update(ctx context.Context, x *catalog.Tax) error {
	q, err := r.t.queries(ctx, x.OrganizationID)
	if err != nil {
		return err
	}
	var n int64
	err = r.t.guard(ctx, func() (err error) {
		n, err = q.UpdateTax(ctx, db.UpdateTaxParams(taxParams(x)))
		return err
	})
	return updateErr("tax", x.ID, n, err)
}

// Delete removes the tax; the join tables of its owners cascade. The
