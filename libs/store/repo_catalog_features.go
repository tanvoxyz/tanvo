func entitlementParams(e *catalog.Entitlement) (db.CreateEntitlementParams, error) {
	values := e.Values
	if values == nil {
		values = map[string]string{}
	}
	b, err := encodeJSON(values)
	if err != nil {
		return db.CreateEntitlementParams{}, fmt.Errorf("entitlement %s: %w", e.ID, err)
	}
	return db.CreateEntitlementParams{
		OrganizationID:  e.OrganizationID.UUID(),
		ID:              e.ID.UUID(),
		FeatureID:       e.FeatureID.UUID(),
		PlanID:          optUUID(e.PlanID),
		SubscriptionID:  optUUID(e.SubscriptionID),
		PrivilegeValues: b,
		CreatedAt:       utc(e.CreatedAt),
		UpdatedAt:       utc(e.UpdatedAt),
	}, nil
}

func entitlementOf(r db.Entitlement) (*catalog.Entitlement, error) {
	var values map[string]string
	if err := decodeJSON(r.PrivilegeValues, &values); err != nil {
		return nil, fmt.Errorf("entitlement %s: %w", r.ID, err)
	}
	if len(values) == 0 {
		values = nil
	}
	return &catalog.Entitlement{
		ID:             idOf[core.EntitlementID](r.ID),
		OrganizationID: idOf[core.OrganizationID](r.OrganizationID),
		FeatureID:      idOf[core.FeatureID](r.FeatureID),
		PlanID:         optIDOf[core.PlanID](r.PlanID),
		SubscriptionID: optIDOf[core.SubscriptionID](r.SubscriptionID),
		Values:         values,
		CreatedAt:      utc(r.CreatedAt),
		UpdatedAt:      utc(r.UpdatedAt),
		DeletedAt:      optUTC(r.DeletedAt),
	}, nil
}

