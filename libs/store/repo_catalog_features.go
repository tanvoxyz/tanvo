func (r taxRepo) ListByCodes(ctx context.Context, org core.OrganizationID, codes []string) ([]*catalog.Tax, error) {
	q, err := r.t.queries(ctx, org)
	if err != nil {
		return nil, err
	}
	rows, err := q.ListTaxesByCodes(ctx, db.ListTaxesByCodesParams{OrganizationID: org.UUID(), Codes: codes})
	if err != nil {
		return nil, fmt.Errorf("list taxes: %w", mapErr(err))
	}
	taxes, err := convAll(rows, taxOf)
	if err != nil {
		return nil, err
	}
	byCode := make(map[string]*catalog.Tax, len(taxes))
	for _, x := range taxes {
		byCode[x.Code] = x
	}
	return catalogFeaturesInOrder("tax", codes, byCode)
}

