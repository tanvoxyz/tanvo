// catalogFeaturesEntitlement returns an unsaved entitlement of feature for
// plan (or for sub when it is not nil).
func catalogFeaturesEntitlement(e *env, f *catalog.Feature, plan *catalog.Plan, sub *subscription.Subscription, values map[string]string) *catalog.Entitlement {
	en := &catalog.Entitlement{
		ID:             core.NewID[core.EntitlementID](e.ids),
		OrganizationID: f.OrganizationID,
		FeatureID:      f.ID,
		Values:         values,
		CreatedAt:      now,
		UpdatedAt:      now,
	}
	if sub != nil {
		en.SubscriptionID = sub.ID
	} else {
		en.PlanID = plan.ID
	}
	return en
}

// catalogFeaturesRemoval returns an unsaved removal of feature (or of one
// of its privileges) for sub.
func catalogFeaturesRemoval(e *env, f *catalog.Feature, sub *subscription.Subscription, privilege string) *catalog.EntitlementRemoval {
	return &catalog.EntitlementRemoval{
		ID:             core.NewID[core.EntitlementRemovalID](e.ids),
		OrganizationID: f.OrganizationID,
		SubscriptionID: sub.ID,
		FeatureID:      f.ID,
		PrivilegeCode:  privilege,
		CreatedAt:      now,
	}
}

