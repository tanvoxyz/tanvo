// catalogPart2Data holds the tables of taxes, commitments, usage
// thresholds, features and entitlements of package catalog.
type catalogPart2Data struct {
	taxes        *table[core.TaxID, catalog.Tax]
	commitments  *table[core.CommitmentID, catalog.Commitment]
	thresholds   *table[core.UsageThresholdID, catalog.UsageThreshold]
	features     *table[core.FeatureID, catalog.Feature]
	entitlements *table[core.EntitlementID, catalog.Entitlement]
	removals     *table[core.EntitlementRemovalID, catalog.EntitlementRemoval]
}

func newCatalogPart2Data() *catalogPart2Data {
	return &catalogPart2Data{
		taxes: newTable[core.TaxID, catalog.Tax](nil),
		commitments: newTable[core.CommitmentID](func(c catalog.Commitment) catalog.Commitment {
			c.TaxIDs = slices.Clone(c.TaxIDs)
			return c
		}),
		thresholds: newTable[core.UsageThresholdID, catalog.UsageThreshold](nil),
		features: newTable[core.FeatureID](func(f catalog.Feature) catalog.Feature {
			f.Privileges = slices.Clone(f.Privileges)
			for i := range f.Privileges {
				f.Privileges[i].SelectOptions = slices.Clone(f.Privileges[i].SelectOptions)
			}
			return f
		}),
		entitlements: newTable[core.EntitlementID](func(e catalog.Entitlement) catalog.Entitlement {
			e.Values = maps.Clone(e.Values)
			return e
		}),
		removals: newTable[core.EntitlementRemovalID, catalog.EntitlementRemoval](nil),
	}
}

func (d *catalogPart2Data) snapshot() *catalogPart2Data {
	return &catalogPart2Data{
		taxes:        d.taxes.snapshot(),
		commitments:  d.commitments.snapshot(),
		thresholds:   d.thresholds.snapshot(),
		features:     d.features.snapshot(),
		entitlements: d.entitlements.snapshot(),
		removals:     d.removals.snapshot(),
	}
}

// taxRepo implements catalog.TaxRepository.
type taxRepo struct{ d *catalogPart2Data }

func (r taxRepo) check(t *catalog.Tax) error {
	if r.d.taxes.any(func(x *catalog.Tax) bool {
		return x.ID != t.ID && x.OrganizationID == t.OrganizationID && x.Code == t.Code
	}) {
		return conflict("tax", "code")
	}
	return nil
}

func (r taxRepo) Create(_ context.Context, t *catalog.Tax) error {
	if r.d.taxes.has(t.ID) {
		return conflict("tax", "id")
	}
	if err := r.check(t); err != nil {
		return err
	}
	r.d.taxes.put(t.ID, *t)
	return nil
}

func (r taxRepo) Update(ctx context.Context, t *catalog.Tax) error {
	if _, err := r.Get(ctx, t.OrganizationID, t.ID); err != nil {
		return err
	}
	if err := r.check(t); err != nil {
		return err
	}
	r.d.taxes.put(t.ID, *t)
	return nil
}

func (r taxRepo) Delete(ctx context.Context, org core.OrganizationID, id core.TaxID) error {
	if _, err := r.Get(ctx, org, id); err != nil {
		return err
	}
	r.d.taxes.del(id)
	return nil
}

func (r taxRepo) Get(_ context.Context, org core.OrganizationID, id core.TaxID) (*catalog.Tax, error) {
	t, ok := r.d.taxes.get(id)
	if !ok || t.OrganizationID != org {
		return nil, notFound("tax", id)
	}
	return t, nil
}

func (r taxRepo) GetByCode(_ context.Context, org core.OrganizationID, code string) (*catalog.Tax, error) {
	t, ok := r.d.taxes.first(func(x *catalog.Tax) bool { return x.OrganizationID == org && x.Code == code })
	if !ok {
		return nil, notFound("tax", stringer(code))
	}
	return t, nil
}

func (r taxRepo) ListByCodes(ctx context.Context, org core.OrganizationID, codes []string) ([]*catalog.Tax, error) {
	out := make([]*catalog.Tax, 0, len(codes))
	for _, c := range codes {
		t, err := r.GetByCode(ctx, org, c)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, nil
}

func (r taxRepo) ListByIDs(ctx context.Context, org core.OrganizationID, ids []core.TaxID) ([]*catalog.Tax, error) {
	out := make([]*catalog.Tax, 0, len(ids))
	for _, id := range ids {
		t, err := r.Get(ctx, org, id)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, nil
}

func (r taxRepo) List(_ context.Context, org core.OrganizationID, f catalog.TaxFilter, page core.PageRequest) (core.Page[*catalog.Tax], error) {
	rows := r.d.taxes.find(func(x *catalog.Tax) bool {
		return x.OrganizationID == org && (f.AutoGenerated == nil || x.AutoGenerated == *f.AutoGenerated)
	})
	return paginate(rows, func(t *catalog.Tax) core.TaxID { return t.ID }, page)
}

