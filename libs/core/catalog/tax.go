// Tax is a tax rate attached to billing entities, customers, plans,
// charges, fixed charges, add-ons and commitments (domain §7.7). Issued
// documents keep snapshots of the taxes they applied, so deleting or
// changing a tax never alters them.
type Tax struct {
	// ID identifies the tax.
	ID core.TaxID
	// OrganizationID is the owning organization.
	OrganizationID core.OrganizationID
	// Code is unique in the organization, ≤ 255 characters.
	Code string
	// Name is required, ≤ 255 characters.
	Name string
	// Rate is the rate in percent, 0 ≤ rate ≤ 100.
	Rate money.Decimal
	// Description is an optional explanation.
	Description *string
	// AutoGenerated marks a tax maintained by EU tax management; it is
	// read-only through the API.
	AutoGenerated bool
	// CreatedAt is the creation instant.
	CreatedAt time.Time
	// UpdatedAt is the instant of the last change.
	UpdatedAt time.Time
}

// Validate checks the invariants of domain §7.7.
func (t *Tax) Validate() error {
	var v core.Validator
	v.Code("code", t.Code, 255)
	v.String("name", t.Name, 255)
	v.Check(!t.Rate.IsNegative() && t.Rate.LessThanOrEqual(money.NewFromInt(100)), "rate", core.CodeOutOfRange)
	return v.Err()
}

// Codes of the taxes maintained by EU tax management (domain §22.10). The
// country-specific codes are built by [EUStandardTaxCode] and
// [EUExceptionTaxCode]. [Change] Lago prefixes them with "lago_".
const (
	// EUReverseChargeTaxCode is the 0% tax of intra-EU B2B sales with a
	// valid VIES number in another country.
	EUReverseChargeTaxCode = "eu_reverse_charge"
	// EUTaxExemptCode is the 0% tax of customers outside the EU.
	EUTaxExemptCode = "eu_tax_exempt"
)

// EUTaxKind is the kind of an EU tax management code.
type EUTaxKind int

// EUTaxKind values.
const (
	// EUTaxStandard is a country's standard rate: eu_<country>_standard.
	EUTaxStandard EUTaxKind = iota + 1
	// EUTaxException is a territory exception of a country:
	// eu_<country>_exception_<territory>.
	EUTaxException
	// EUTaxReverseCharge is [EUReverseChargeTaxCode].
	EUTaxReverseCharge
	// EUTaxExempt is [EUTaxExemptCode].
	EUTaxExempt
)

// EUTaxCode is a parsed EU tax management code.
type EUTaxCode struct {
	// Kind is the kind of tax.
	Kind EUTaxKind
	// Country is the upper-case ISO 3166-1 alpha-2 country, for standard
	// and exception taxes.
	Country string
	// Territory is the snake_case territory of an exception tax.
	Territory string
}

// EUStandardTaxCode returns the code of country's standard rate tax, for
// example "eu_fr_standard".
func EUStandardTaxCode(country string) string {
	return "eu_" + strings.ToLower(country) + "_standard"
}

// EUExceptionTaxCode returns the code of the tax of a territory exception
// of country, for example "eu_de_exception_heligoland". territory is the
// territory's name as published in the EU VAT rate table; it is
// transliterated and snake-cased by [EUTerritorySlug].
func EUExceptionTaxCode(country, territory string) string {
	return "eu_" + strings.ToLower(country) + "_exception_" + EUTerritorySlug(territory)
}

// EUStandardTaxName returns the display name of country's standard tax,
// "FR Standard".
func EUStandardTaxName(country string) string { return strings.ToUpper(country) + " Standard" }

// EUExceptionTaxName returns the display name of a territory exception
// tax, "DE Heligoland Standard".
func EUExceptionTaxName(country, territory string) string {
	return strings.ToUpper(country) + " " + territory + " Standard"
}

// EUTerritorySlug turns a territory name into the snake_case suffix of an
// exception tax code: Latin letters lose their diacritics, other runs of
// characters become one "_" ("Åland Islands" → "aland_islands").
func EUTerritorySlug(name string) string {
	var b strings.Builder
	sep := false
	for _, r := range strings.ToLower(name) {
		if f, ok := taxFoldLatin(r); ok {
			r = f
		}
		if r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			if sep && b.Len() > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
			sep = false
			continue
		}
		sep = true
	}
	return b.String()
}

// ParseEUTaxCode parses an EU tax management code; ok is false for any
// other code.
func ParseEUTaxCode(code string) (c EUTaxCode, ok bool) {
	switch code {
	case EUReverseChargeTaxCode:
		return EUTaxCode{Kind: EUTaxReverseCharge}, true
	case EUTaxExemptCode:
		return EUTaxCode{Kind: EUTaxExempt}, true
	}
	rest, found := strings.CutPrefix(code, "eu_")
	if !found || len(rest) < 3 || rest[2] != '_' {
		return EUTaxCode{}, false
	}
	country := strings.ToUpper(rest[:2])
	if !core.IsEUCountry(country) {
		return EUTaxCode{}, false
	}
	switch suffix := rest[3:]; {
	case suffix == "standard":
		return EUTaxCode{Kind: EUTaxStandard, Country: country}, true
	case strings.HasPrefix(suffix, "exception_") && len(suffix) > len("exception_"):
		return EUTaxCode{Kind: EUTaxException, Country: country, Territory: suffix[len("exception_"):]}, true
	default:
		return EUTaxCode{}, false
	}
}

// String returns the code of c.
func (c EUTaxCode) String() string {
	switch c.Kind {
	case EUTaxStandard:
		return EUStandardTaxCode(c.Country)
	case EUTaxException:
		return "eu_" + strings.ToLower(c.Country) + "_exception_" + c.Territory
	case EUTaxReverseCharge:
		return EUReverseChargeTaxCode
	case EUTaxExempt:
		return EUTaxExemptCode
	default:
		return ""
	}
}

// taxFoldLatin maps a lower-case Latin letter with a diacritic to its base
// letter.
func taxFoldLatin(r rune) (rune, bool) {
	const from = "àáâãäåāăąçćčďèéêëēęěìíîïīľĺłñńňòóôõöøōőŕřśšşťţùúûüūůűýÿźżž"
	const to = "aaaaaaaaaccc" + "deeeeeeeiiiiilllnnnoooooooorrsssttuuuuuuuyyzzz"
	i := 0
	for _, f := range from {
		if f == r {
			return rune(to[i]), true
		}
		i++
	}
	return r, false
}

// TaxCandidates are the tax lists a fee can inherit, one per level of the
// resolution of domain §22.10. A nil or empty list means the level has no
// taxes; levels that do not apply to the fee's type are ignored.
type TaxCandidates struct {
	// Explicit are the taxes named on a one-off invoice line.
	Explicit []core.TaxID
	// AddOn are the taxes of the fee's add-on (add-on and fixed-charge
	// fees).
	AddOn []core.TaxID
	// Charge are the taxes of the fee's charge (charge and product fees).
	Charge []core.TaxID
	// FixedCharge are the taxes of the fee's fixed charge.
	FixedCharge []core.TaxID
	// Commitment are the taxes of the fee's commitment.
	Commitment []core.TaxID
	// Plan are the taxes of the subscription's plan (subscription, charge,
	// fixed-charge, commitment and product fees).
	Plan []core.TaxID
	// Customer are the customer's taxes.
	Customer []core.TaxID
	// BillingEntity are the billing entity's default taxes.
	BillingEntity []core.TaxID
}

// ResolveTaxes returns the taxes of a fee of type t: the first non-empty
// list, in the order of domain §22.10, among the levels that apply to t,
// and the level it came from. Credit fees (wallet purchases) are never
// taxed: the result is nil with an empty source. Product fees resolve like
// charge fees.
func ResolveTaxes(t core.FeeType, c TaxCandidates) ([]core.TaxID, TaxSource) {
	if t == core.FeeTypeCredit {
		return nil, ""
	}
	onPlan := t == core.FeeTypeSubscription || t == core.FeeTypeCharge || t == core.FeeTypeFixedCharge ||
		t == core.FeeTypeCommitment || t == core.FeeTypeProduct
	levels := []struct {
		applies bool
		taxes   []core.TaxID
		source  TaxSource
	}{
		{true, c.Explicit, TaxSourceExplicit},
		{t == core.FeeTypeAddOn || t == core.FeeTypeFixedCharge, c.AddOn, TaxSourceAddOn},
		{t == core.FeeTypeCharge || t == core.FeeTypeProduct, c.Charge, TaxSourceCharge},
		{t == core.FeeTypeFixedCharge, c.FixedCharge, TaxSourceFixedCharge},
		{t == core.FeeTypeCommitment, c.Commitment, TaxSourceCommitment},
		{onPlan, c.Plan, TaxSourcePlan},
		{true, c.Customer, TaxSourceCustomer},
		{true, c.BillingEntity, TaxSourceBillingEntity},
	}
	for _, l := range levels {
		if l.applies && len(l.taxes) > 0 {
			return l.taxes, l.source
		}
	}
	return nil, ""
}
