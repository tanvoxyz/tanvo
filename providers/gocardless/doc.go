// Package gocardless is the GoCardless adapter of the payment provider port
// ([payment.Gateway], architecture §12): OAuth connection, customers,
// direct debit mandate setup through billing requests, payments against a
// mandate, cancellations, refunds of credit notes, and verification and
// decoding of webhooks.
//
// # Client
//
// Calls go through the official github.com/gocardless/gocardless-pro-go
// (MIT), configured per call with the connection's access token over one
// shared HTTP client, whose transport adds a per-connection rate limit and
// OpenTelemetry instrumentation through the injected providers. The
// client's in-process retries are disabled: they resend a request whose
// body was already read (retries.go try, payment_service.go Create), so a
// failure worth retrying is returned as a [payment.ErrRetryable] provider
// error and retried by the caller's job with the same idempotency key.
//
// # Settings and secrets
//
// A connection's settings object holds "success_redirect_url"; its secrets
// object holds "access_token", obtained with [Gateway.ExchangeCode] from
// the OAuth callback, and "webhook_secret", generated by
// [Gateway.RegisterWebhook] for the merchant to enter in its GoCardless
// webhook endpoint. A live access token ("live_…") calls GoCardless' live
// environment, any other its sandbox.
//
// # Payment methods
//
// A GoCardless payment method is a mandate. SetupURL returns a billing
// request flow that sets one up; its mandates "created" webhook yields
// [payment.PaymentMethodAttached] with the mandate's customer, and an
// API-originated "cancelled" one [payment.PaymentMethodDetached].
//
// # Differences from lago
//
// Each deliberate difference is noted where it is implemented, with its
// lago reference, and listed in docs/parity.md §1.34–1.35.
