// restTax is the JSON of a tax in a REST response.
type restTax struct {
	ID            string `json:"id"`
	Code          string `json:"code"`
	Name          string `json:"name"`
	Rate          string `json:"rate"`
	Description   string `json:"description"`
	AutoGenerated bool   `json:"auto_generated"`
	CreatedAt     string `json:"created_at"`

	AppliedToOrganization         bool     `json:"applied_to_organization"`
	AppliedToBillingEntitiesCodes []string `json:"applied_to_billing_entities_codes"`
}

type restTaxBody struct {
	Tax restTax `json:"tax"`
}

