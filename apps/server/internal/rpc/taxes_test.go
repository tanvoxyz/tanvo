func TestDeleteTax(t *testing.T) {
	t.Parallel()
	t.Run("deletes it and detaches it", func(t *testing.T) {
		t.Parallel()
		// source: spec/requests/api/v1/taxes_controller_spec.rb:136
		// source: spec/requests/api/v1/taxes_controller_spec.rb:140
		s := rpctest.New(t)
		vat := s.Fixtures.Tax("vat", "20")
		s.Fixtures.AddOn(100, func(a *catalog.AddOn) { a.TaxIDs = []core.TaxID{vat.ID} })
		status, body := s.REST(t, s.APIKey, http.MethodDelete, "/v1/taxes/code%3Avat", nil)
		if status != http.StatusOK {
			t.Fatalf("got status = %d (%s), want = 200", status, body)
		}
		if got := decode[restTaxBody](t, body).Tax; got.ID != vat.ID.String() || got.Code != "vat" {
			t.Errorf("got %s/%s, want = %s/vat", got.ID, got.Code, vat.ID)
		}
		// Discarded rows are kept for history; count the kept ones.
		for table, want := range map[string]int{"taxes WHERE deleted_at IS NULL AND": 0, "add_on_taxes WHERE": 0, "add_ons WHERE deleted_at IS NULL AND": 1} {
			var n int
			if err := s.Admin.QueryRow(t.Context(), "SELECT count(*) FROM "+table+" organization_id = $1", s.Org.ID.UUID()).Scan(&n); err != nil {
				t.Fatal(err)
			}
			if n != want {
				t.Errorf("got %s = %d, want = %d", table, n, want)
			}
		}
	})
	t.Run("not found", func(t *testing.T) {
		t.Parallel()
		// source: spec/requests/api/v1/taxes_controller_spec.rb:151
		s := rpctest.New(t)
		status, body := s.REST(t, s.APIKey, http.MethodDelete, "/v1/taxes/code%3Aunknown", nil)
		if status != http.StatusNotFound {
			t.Fatalf("got status = %d (%s), want = 404", status, body)
		}
	})
}

func TestListTaxes(t *testing.T) {
	t.Parallel()
	s := rpctest.New(t)
	b := s.Fixtures.Tax("b", "20", func(x *catalog.Tax) { x.Name = "B" })
	s.Clock.Advance(time.Second)
	a := s.Fixtures.Tax("a", "10", func(x *catalog.Tax) { x.Name = "A"; x.AutoGenerated = true })
	s.Fixtures.UpdateBillingEntity(func(be *organization.BillingEntity) { be.TaxIDs = []core.TaxID{a.ID} })

	type page struct {
		Taxes         []restTax `json:"taxes"`
		NextPageToken string    `json:"next_page_token"`
	}
	list := func(t *testing.T, query string) page {
		t.Helper()
		status, body := s.REST(t, s.APIKey, http.MethodGet, "/v1/taxes"+query, nil)
		if status != http.StatusOK {
			t.Fatalf("got status = %d (%s), want = 200", status, body)
		}
		return decode[page](t, body)
	}
	ids := func(p page) []string {
		out := make([]string, len(p.Taxes))
		for i, x := range p.Taxes {
			out[i] = x.ID
		}
		return out
	}
	tests := []struct {
		name   string
		source string
		query  string
		want   []string
	}{
		{"by name", "spec/requests/api/v1/taxes_controller_spec.rb:165", "", []string{a.ID.String(), b.ID.String()}},
		{"auto generated", "spec/queries/taxes_query_spec.rb:132", "?filter=auto_generated%3Dtrue", []string{a.ID.String()}},
		{"applied to organization", "spec/queries/taxes_query_spec.rb:123", "?filter=applied_to_organization%3Dtrue", []string{a.ID.String()}},
		{"not applied to organization", "spec/queries/taxes_query_spec.rb:100", "?filter=applied_to_organization%3Dfalse", []string{b.ID.String()}},
		{"search", "spec/queries/taxes_query_spec.rb:92", "?search=B", []string{b.ID.String()}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Logf("source: %s", tt.source)
			got := ids(list(t, tt.query))
			if len(got) != len(tt.want) || (len(got) > 0 && got[0] != tt.want[0]) {
				t.Errorf("got = %v, want = %v", got, tt.want)
			}
		})
	}
	t.Run("applied to the default billing entity", func(t *testing.T) {
		t.Log("source: spec/requests/api/v1/taxes_controller_spec.rb:179")
		for _, x := range list(t, "").Taxes {
			applied := x.ID == a.ID.String()
			if x.AppliedToOrganization != applied || (len(x.AppliedToBillingEntitiesCodes) == 1) != applied {
				t.Errorf("tax %s: got applied = %t, %v, want applied = %t", x.Code, x.AppliedToOrganization, x.AppliedToBillingEntitiesCodes, applied)
			}
		}
	})
	t.Run("pagination", func(t *testing.T) {
		// source: spec/requests/api/v1/taxes_controller_spec.rb:192
		first := list(t, "?page_size=1")
		if len(first.Taxes) != 1 || first.NextPageToken == "" {
			t.Fatalf("got %d taxes, token %q, want 1 and a token", len(first.Taxes), first.NextPageToken)
		}
		second := list(t, "?page_size=1&page_token="+first.NextPageToken)
		if got := ids(second); len(got) != 1 || got[0] != b.ID.String() {
			t.Errorf("got = %v, want = [%s]", got, b.ID)
		}
	})
}
